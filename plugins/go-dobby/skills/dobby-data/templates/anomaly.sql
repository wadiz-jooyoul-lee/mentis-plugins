-- anomaly.sql — 이번 기간 daily 이벤트를 유난히 많이 남긴 기기(로봇 후보) 상위 20개.
-- 결과 칸 순서(바꾸지 말 것): deviceid, ua, dtype, n, days
WITH ev AS (
  SELECT CREATEDAT_DATE, DEVICEID, USERAGENT, DEVICETYPE FROM WADIZ_LIVE.WADITAG.TAGEVENT
  WHERE CREATEDAT >= '{{FROM}}' AND CREATEDAT < '{{TO}}' AND DEVICETYPE IN ({{DEVICE_TYPES}})
    AND ({{DAILY_COND}}) AND DEVICEID IS NOT NULL
), excluded AS (
{{EXCLUDED}}
)
SELECT DEVICEID deviceid, LEFT(MAX(USERAGENT), 160) ua, MAX(DEVICETYPE) dtype, COUNT(*) n, COUNT(DISTINCT CREATEDAT_DATE) days
FROM ev WHERE DEVICEID NOT IN (SELECT DEVICEID FROM excluded)
GROUP BY 1 HAVING COUNT(*) >= {{MIN_EVENTS}}
ORDER BY n DESC LIMIT 20
